"""情节消化 Prompt：把自然语言情节描述整理成 idea。

设计原则（响应用户反馈调整）：
- 数量忠于原文（1个就1个，10个就10个）
- 核心设定、人物动机、情节走向必须忠实原文，不得篡改或"理解偏差"
- 在原文明确模糊处允许适度具体化（给个具体名字/场景细节），但不得改变原意
- 允许在原文基础上做合理的场景延展（如加环境细节），但不能改变情节走向
"""

DIGEST_SYSTEM = """你是一位经验丰富的小说策划助理。你的职责是把作者描述的情节，整理成结构化的创作素材。

你的核心原则：
1. 【忠实核心】作者的情节走向、人物动机、关键设定，你必须原样理解，不得自行篡改或"重新解读"
2. 【适度延展】在不改变原意的前提下，可以为模糊之处补充具体细节（如给"某种武器"起个名字），可以为场景增加环境描写
3. 【不得偏题】绝对不可以改变作者设定的情节走向、人物关系、核心冲突

你只输出严格的 JSON，不解释。"""


def digest_plot_prompt(
    raw_text: str,
    project_meta: str,
    outline_text: str,
    existing_chars: list[str],
) -> list[tuple[str, str]]:
    """把一段自然语言情节描述，整理成 idea。"""
    chars = "、".join(existing_chars) if existing_chars else "(从描述中识别)"
    return [
        (
            "user",
            f"""请把下面这段作者描述的【情节】，整理成结构化 idea 条目。

【当前项目】
{project_meta}

【现有大纲（参考用）】
{outline_text}

【已知人物】{chars}

【作者描述的情节】
{raw_text}

请输出 JSON（```json 代码块）：
```json
{{
  "ideas": [
    {{
      "title": "点子标题（10字内）",
      "content": "这一点子的内容（忠实复述作者原意，可适度具体化模糊处，但不得改变情节走向和人物动机）",
      "type": "scene|plot|dialogue|twist|character|world|emotion|other",
      "tags": ["标签"],
      "related_chars": ["相关人物"],
      "priority": 1到5,
      "suggested_chapter": "建议章节id（能看出就填，看不出留空）",
      "from_original": "引用原文对应的片段（证明这条来自作者，而非偏离原意）",
      "elaboration": "如果有在原文基础上的延展（具体化/场景补充），在这里说明延展了什么（无延展则留空）"
    }}
  ],
  "new_elements": [
    {{
      "kind": "character|location|faction|lore",
      "name": "原文中出现的新元素名",
      "summary": "根据原文的描述",
      "original_quote": "原文中提到它的句子"
    }}
  ],
  "count_note": "实际拆出的 idea 数量说明（如'原文含3个独立点子'）"
}}
```

【拆解规则】

1. **数量忠于原文**：
   - 原文里有几个独立点子就拆几条 idea
   - 1个点子→1条，8个点子→8条
   - 不为凑数而强拆，也不把多个独立点子合并

2. **核心必须忠实**（这是最重要的规则）：
   - 作者写的情节走向、人物动机、关键设定，必须原样保留，不得"重新解读"
   - ❌ 错误示范：作者写"沈渡为了保护造梦机逃亡"，你理解成"沈渡想利用造梦机获利"——这是篡改动机
   - ❌ 错误示范：作者写"主角与反派是兄弟"，你"延展"成"主角其实是反派的克隆"——这是改变设定
   - ✅ 正确：原样保留作者的核心意图，只整理不重写

3. **允许的适度延展**（仅限以下情况）：
   - 原文用了模糊代词（"某种武器""某个地方""某段时间"）→ 可以给一个具体名字
   - 原文场景描写单薄 → 可以为场景补充环境细节（光影/声音/气味）
   - 原文对话只有梗概 → 可以补充几句具体对白
   - 但所有延展不得改变情节走向、人物关系、核心冲突
   - 有延展时必须在 elaboration 字段说明延展了什么

4. **from_original 必填**：每条 idea 必须引用原文片段，证明核心来自作者。

5. **new_elements 只记原文提到的**：不要"建议"作者增加新人物，只整理原文里实际出现的。""",
        )
    ]
